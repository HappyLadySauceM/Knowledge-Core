use std::{env, error::Error, fs, path::PathBuf};

const USAGE: &str = "usage: knowledge-core-rust-codegen [--root <repository-root>]";

fn main() -> Result<(), Box<dyn Error>> {
    let root = parse_root(env::args().skip(1))?;
    let idl_root = root.join("idl/rpc/v1");
    let output = root.join("services/collaboration/src/generated");

    for required in [
        idl_root.join("common.thrift"),
        idl_root.join("knowledge.thrift"),
        idl_root.join("collaboration.thrift"),
    ] {
        if !required.is_file() {
            return Err(format!("required IDL is missing: {}", required.display()).into());
        }
    }

    volo_build::Builder::thrift()
        .add_service(idl_root.join("collaboration.thrift"))
        .add_service(idl_root.join("knowledge.thrift"))
        .include_dirs(vec![idl_root])
        .out_dir(&output)
        .filename(PathBuf::from("volo_gen.rs"))
        .write()?;
    fs::write(
        output.join("mod.rs"),
        "// Code generated by knowledge-core-rust-codegen. DO NOT EDIT.\n\
         #![allow(unsafe_code, clippy::all, clippy::pedantic)]\n\
         include!(\"volo_gen.rs\");\n\
         pub use volo_gen::{collaboration, common, knowledge};\n",
    )?;

    Ok(())
}

fn parse_root(args: impl Iterator<Item = String>) -> Result<PathBuf, Box<dyn Error>> {
    let mut root = env::current_dir()?;
    let mut args = args.peekable();

    while let Some(argument) = args.next() {
        match argument.as_str() {
            "--root" => {
                let value = args.next().ok_or(USAGE)?;
                root = PathBuf::from(value);
            }
            "-h" | "--help" => {
                println!("{USAGE}");
                std::process::exit(0);
            }
            _ => return Err(format!("unknown argument {argument:?}; {USAGE}").into()),
        }
    }

    root.canonicalize()
        .map_err(|error| format!("resolve repository root {}: {error}", root.display()).into())
}

#[cfg(test)]
mod tests {
    use super::parse_root;

    #[test]
    fn rejects_unknown_arguments() {
        let error = parse_root(["--unknown".to_owned()].into_iter()).unwrap_err();
        assert!(error.to_string().contains("unknown argument"));
    }
}
