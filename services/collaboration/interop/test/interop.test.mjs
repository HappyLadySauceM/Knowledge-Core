test("official Yjs applies the committed Yrs update-v1 fixture", async () => {
  const fixture = await readFixture("yrs-update-v1.json");
  const document = new Y.Doc();
  Y.applyUpdate(document, Buffer.from(fixture.state_base64, "base64"));

  assert.equal(
    document.getXmlFragment(FRAGMENT_NAME).toString(),
    fixture.expected_xml,
  );
});

test("committed fixture is generated by official Yjs and y-prosemirror", async () => {
  const fixture = await readFixture("yjs-update-v1.json");
  assert.deepEqual(fixture, createYjsFixture());

  const document = new Y.Doc();
  Y.applyUpdate(document, Buffer.from(fixture.state_base64, "base64"));
  const projection = yXmlFragmentToProseMirrorRootNode(
    document.getXmlFragment(FRAGMENT_NAME),
    richTextSchema,
  ).toJSON();

  assert.deepEqual(toJsonValue(projection), fixture.projection);
  assert.deepEqual(
    toJsonValue(richTextSchema.nodeFromJSON(fixture.projection).toJSON()),
    fixture.projection,
  );
});

